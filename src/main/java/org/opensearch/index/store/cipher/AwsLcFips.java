    private static final byte[] CTR_IV = HEX.parseHex("f0f1f2f3f4f5f6f7f8f9fafbfcfdfeff");
    private static final byte[] CTR_PLAINTEXT = HEX.parseHex("6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e51");
    private static final byte[] CTR_EXPECTED = HEX.parseHex("601ec313775789a5b7a7f504bbf3d228f443e3ca4d62b59aca84e990cacaf5c5");

    /** Known-answer and round-trip tests through this binding; throws {@link IllegalStateException} on failure. */
    void selfTest() {
        try {
            Key zero = new javax.crypto.spec.SecretKeySpec(new byte[KEY_LENGTH], "AES");
            MemorySegment noAad = MemorySegment.ofArray(new byte[0]);

            byte[] entry = new byte[ENTRY_LENGTH];
            System.arraycopy(GCM_KAT_TAG, 0, entry, NONCE_LENGTH, TAG_LENGTH);
            byte[] plain = new byte[AES_BLOCK];
            open(zero, noAad, MemorySegment.ofArray(GCM_KAT.clone()), MemorySegment.ofArray(entry), MemorySegment.ofArray(plain));
            require(Arrays.equals(new byte[AES_BLOCK], plain), "AES-256-GCM known-answer test");

            byte[] aad = new byte[8];
            byte[] sealed = new byte[AES_BLOCK];
            byte[] sealedEntry = new byte[ENTRY_LENGTH];
            seal(
                zero,
                MemorySegment.ofArray(aad),
                MemorySegment.ofArray(new byte[AES_BLOCK]),
                MemorySegment.ofArray(sealed),
                MemorySegment.ofArray(sealedEntry)
            );
            byte[] roundTrip = new byte[AES_BLOCK];
            open(
                zero,
                MemorySegment.ofArray(aad),
                MemorySegment.ofArray(sealed),
                MemorySegment.ofArray(sealedEntry),
                MemorySegment.ofArray(roundTrip)
            );
            require(Arrays.equals(new byte[AES_BLOCK], roundTrip), "AES-256-GCM seal round trip");
            require(
                Arrays.equals(new byte[NONCE_LENGTH], Arrays.copyOf(sealedEntry, NONCE_LENGTH)) == false,
                "AES-256-GCM nonce generation"
            );

            Key ctrKey = new javax.crypto.spec.SecretKeySpec(CTR_KEY, "AES");
            byte[] buf = CTR_PLAINTEXT.clone();
            ctr(ctrKey, CTR_IV, 0, MemorySegment.ofArray(buf));
            require(MessageDigest.isEqual(CTR_EXPECTED, buf), "AES-256-CTR known-answer test");
            byte[] tail = Arrays.copyOfRange(CTR_PLAINTEXT, 5, CTR_PLAINTEXT.length);
            ctr(ctrKey, CTR_IV, 5, MemorySegment.ofArray(tail));
            require(MessageDigest.isEqual(Arrays.copyOfRange(CTR_EXPECTED, 5, CTR_EXPECTED.length), tail), "AES-256-CTR offset test");
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException("AWS-LC FIPS self-test failed", e);
        }
    }

    private static void require(boolean ok, String what) {
        if (ok == false) {
            throw new IllegalStateException(what + " failed for the AWS-LC FIPS module");
        }
    }

    // ---- error handling ----

    private void check(int rc, String what) throws GeneralSecurityException {
        if (rc != 1) {
            throw new GeneralSecurityException(describe(what));
        }
    }

    /** "what failed: <AWS-LC error queue>", clearing the queue. */
    private String describe(String what) {
        StringBuilder sb = new StringBuilder(what).append(" failed");
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment buf = arena.allocate(256);
            int code;
            String sep = ": ";
            while ((code = (int) errGetError.invokeExact()) != 0) {
                MemorySegment ignored = (MemorySegment) errString.invokeExact(code, buf, 256L);
                sb.append(sep).append(cString(buf));
                sep = "; ";
            }
        } catch (Throwable ignored) {
            // the description is best effort
        }
        return sb.toString();
    }

    private void clearErrors() {
        try {
            errClear.invokeExact();
        } catch (Throwable ignored) {
            // best effort
        }
    }

    private static String cString(MemorySegment s) {
        return s.reinterpret(Long.MAX_VALUE).getString(0, StandardCharsets.UTF_8);
    }

    private static MethodHandle handle(Linker linker, SymbolLookup lib, String name, FunctionDescriptor fd, Linker.Option... options) {
        MemorySegment symbol = lib.find(name).orElseThrow(() -> new IllegalStateException("AWS-LC library has no symbol " + name));
        return linker.downcallHandle(symbol, fd, options);
    }
