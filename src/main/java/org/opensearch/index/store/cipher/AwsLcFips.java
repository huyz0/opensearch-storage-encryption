    /**
     * Encrypts {@code in} with AES-256-GCM under a nonce the module generates.
     *
     * @param key   AES-256 key
     * @param aad   additional authenticated data
     * @param in    plaintext
     * @param out   receives the ciphertext, {@code in.byteSize()} bytes; may be the same memory as {@code in}
     * @param entry receives the 12-byte nonce followed by the 16-byte tag
     */
    public void seal(Key key, MemorySegment aad, MemorySegment in, MemorySegment out, MemorySegment entry) throws GeneralSecurityException {
        checkSizes(in, out, entry);
        ThreadState s = state.get();
        MemorySegment ctx = s.aeadContext(key);
        try {
            int rc = (int) sealScatter
                .invokeExact(
                    ctx,
                    out,
                    s.tagAndNonce,
                    s.sizeOut,
                    (long) ENTRY_LENGTH,
                    MemorySegment.NULL,
                    0L,
                    in,
                    in.byteSize(),
                    MemorySegment.NULL,
                    0L,
                    aad,
                    aad.byteSize()
                );
            check(rc, "AES-256-GCM seal");
            if (s.sizeOut.get(ValueLayout.JAVA_LONG, 0) != ENTRY_LENGTH) {
                throw new IllegalStateException("AES-256-GCM seal returned " + s.sizeOut.get(ValueLayout.JAVA_LONG, 0) + " tag bytes");
            }
            // The module writes tag || nonce; the plugin stores nonce || tag.
            MemorySegment.copy(s.tagAndNonce, TAG_LENGTH, entry, 0, NONCE_LENGTH);
            MemorySegment.copy(s.tagAndNonce, 0, entry, NONCE_LENGTH, TAG_LENGTH);
        } catch (GeneralSecurityException | RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    /**
     * Decrypts and authenticates AES-256-GCM. On failure {@code out} is zero-filled.
     *
     * @param entry the 12-byte nonce followed by the 16-byte tag, as {@link #seal} wrote them
     * @throws AEADBadTagException if authentication fails
     */
    public void open(Key key, MemorySegment aad, MemorySegment in, MemorySegment entry, MemorySegment out) throws GeneralSecurityException {
        checkSizes(in, out, entry);
        ThreadState s = state.get();
        MemorySegment ctx = s.aeadContext(key);
        MemorySegment.copy(entry, NONCE_LENGTH, s.tagAndNonce, 0, TAG_LENGTH);
        MemorySegment.copy(entry, 0, s.tagAndNonce, TAG_LENGTH, NONCE_LENGTH);
        try {
            int rc = (int) openGather
                .invokeExact(ctx, out, MemorySegment.NULL, 0L, in, in.byteSize(), s.tagAndNonce, (long) ENTRY_LENGTH, aad, aad.byteSize());
            if (rc != 1) {
                clearErrors();
                throw new AEADBadTagException("Tag mismatch");
            }
        } catch (GeneralSecurityException | RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    /**
     * Applies AES-256-CTR to {@code buf} in place, starting {@code skip} bytes (less than one block) into the
     * key stream of the 16-byte counter block {@code counterBlock}.
     */
    public void ctr(Key key, byte[] counterBlock, int skip, MemorySegment buf) throws GeneralSecurityException {
        if (skip < 0 || skip >= AES_BLOCK) {
            throw new IllegalArgumentException("skip must be in [0, 16): " + skip);
        }
        if (counterBlock.length != AES_BLOCK) {
            throw new IllegalArgumentException("counter block must be 16 bytes");
        }
        if (buf.byteSize() > Integer.MAX_VALUE) {
            throw new IllegalArgumentException("buffer too large: " + buf.byteSize());
        }
        ThreadState s = state.get();
        int len = (int) buf.byteSize();
        try {
            check(
                (int) encryptInit.invokeExact(s.cipherCtx, ctr, MemorySegment.NULL, s.keyBytes(key), MemorySegment.ofArray(counterBlock)),
                "EVP_EncryptInit_ex"
            );
            if (skip > 0) {
                MemorySegment discard = s.ctrScratch.asSlice(AES_BLOCK, AES_BLOCK);
                check((int) encryptUpdate.invokeExact(s.cipherCtx, discard, s.intOut, s.ctrScratch.asSlice(0, skip), skip), "CTR skip");
            }
            if (len > 0) {
                check((int) encryptUpdate.invokeExact(s.cipherCtx, buf, s.intOut, buf, len), "AES-256-CTR");
                int n = s.intOut.get(ValueLayout.JAVA_INT, 0);
                if (n != len) {
                    throw new IllegalStateException("AES-256-CTR produced " + n + " bytes for " + len);
                }
            }
        } catch (GeneralSecurityException | RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    /**
     * SP 800-108 counter-mode KDF with HMAC-SHA-384: {@code K(i) = HMAC(secret, [i]_32 || fixedInput)}.
     *
     * @return {@code length} derived bytes
     */
    public byte[] kbkdfHmacSha384(byte[] secret, byte[] fixedInput, int length) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment out = arena.allocate(length);
            MemorySegment k = arena.allocate(secret.length);
            MemorySegment.copy(secret, 0, k, ValueLayout.JAVA_BYTE, 0, secret.length);
            MemorySegment info = arena.allocate(Math.max(1, fixedInput.length));
            MemorySegment.copy(fixedInput, 0, info, ValueLayout.JAVA_BYTE, 0, fixedInput.length);
            try {
                int rc = (int) kbkdf.invokeExact(out, (long) length, sha384, k, (long) secret.length, info, (long) fixedInput.length);
                if (rc != 1) {
                    throw new IllegalStateException(describe("KBKDF_ctr_hmac"));
                }
                return out.toArray(ValueLayout.JAVA_BYTE);
            } finally {
                k.fill((byte) 0);
                out.fill((byte) 0);
            }
        } catch (RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    /**
     * A {@link SecureRandom} drawing from the module's DRBG ({@link #randomBytes}). It is not registered with the
     * JCE; seeding it has no effect, since the module seeds its DRBG itself.
     */
    public SecureRandom secureRandom() {
        return new ModuleRandom(this);
    }

    private static final class ModuleRandom extends SecureRandom {
        private static final Provider PROVIDER = new Provider("AWS-LC-FIPS", "3.0.0", "AWS-LC FIPS module DRBG (not registered)") {
        };

        ModuleRandom(AwsLcFips module) {
            super(new Spi(module), PROVIDER);
        }

        @Override
        public String getAlgorithm() {
            return "AWS-LC-FIPS-DRBG";
        }
    }

    private static final class Spi extends SecureRandomSpi {
        private final transient AwsLcFips module;

        Spi(AwsLcFips module) {
            this.module = module;
        }

        @Override
        protected void engineSetSeed(byte[] seed) {
            // The module seeds and reseeds its DRBG from its own entropy source.
        }

        @Override
        protected void engineNextBytes(byte[] bytes) {
            module.randomBytes(bytes);
        }

        @Override
        protected byte[] engineGenerateSeed(int numBytes) {
            byte[] seed = new byte[numBytes];
            module.randomBytes(seed);
            return seed;
        }
    }

    /** Fills {@code bytes} from the module's DRBG. */
    public void randomBytes(byte[] bytes) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment buf = arena.allocate(Math.max(1, bytes.length));
            if ((int) randBytes.invokeExact(buf, (long) bytes.length) != 1) {
                throw new IllegalStateException(describe("RAND_bytes"));
            }
            MemorySegment.copy(buf, ValueLayout.JAVA_BYTE, 0, bytes, 0, bytes.length);
        } catch (RuntimeException e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException(t);
        }
    }

    /** Per-thread contexts and scratch, freed when the thread's state becomes unreachable. */
    private final class ThreadState {
        final MemorySegment cipherCtx;
        final MemorySegment tagAndNonce;
        final MemorySegment sizeOut;
        final MemorySegment intOut;
        final MemorySegment ctrScratch;
        /** Holds the address of the cached AEAD context, so the cleaner frees whichever one is current. */
        final MemorySegment aeadSlot;

        Key aeadKey;
        MemorySegment aeadCtx;
        Key ctrKey;
        byte[] ctrKeyBytes;

        ThreadState() {
            Arena arena = Arena.ofAuto();
            this.tagAndNonce = arena.allocate(ENTRY_LENGTH);
            this.sizeOut = arena.allocate(ValueLayout.JAVA_LONG);
            this.intOut = arena.allocate(ValueLayout.JAVA_INT);
            this.ctrScratch = arena.allocate(2 * AES_BLOCK);
            MemorySegment slot = Arena.ofAuto().allocate(ValueLayout.ADDRESS);
            slot.set(ValueLayout.ADDRESS, 0, MemorySegment.NULL);
            this.aeadSlot = slot;
            MemorySegment c;
            try {
                c = (MemorySegment) cipherCtxNew.invokeExact();
            } catch (Throwable t) {
                throw new IllegalStateException(t);
            }
            if (c.equals(MemorySegment.NULL)) {
                throw new IllegalStateException("EVP_CIPHER_CTX_new failed");
            }
            this.cipherCtx = c;
            CLEANER.register(this, new Release(cipherCtxFree, aeadCtxFree, c.address(), slot));
        }

        /** The AEAD context for {@code key}, creating it (and freeing the previous one) when the key changes. */
        MemorySegment aeadContext(Key key) throws GeneralSecurityException {
            if (key == aeadKey && aeadCtx != null) {
                return aeadCtx;
            }
            byte[] raw = encoded(key);
            try {
                MemorySegment ctx = (MemorySegment) aeadCtxNew
                    .invokeExact(aead, MemorySegment.ofArray(raw), (long) KEY_LENGTH, (long) ENTRY_LENGTH);
                if (ctx.equals(MemorySegment.NULL)) {
                    throw new GeneralSecurityException(describe("EVP_AEAD_CTX_new"));
                }
                if (aeadCtx != null) {
                    aeadCtxFree.invokeExact(aeadCtx);
                }
                aeadCtx = ctx;
                aeadKey = key;
                aeadSlot.set(ValueLayout.ADDRESS, 0, ctx);
                return ctx;
            } catch (GeneralSecurityException | RuntimeException e) {
                throw e;
            } catch (Throwable t) {
                throw new IllegalStateException(t);
            } finally {
                Arrays.fill(raw, (byte) 0);
            }
        }

        MemorySegment keyBytes(Key key) throws GeneralSecurityException {
            if (key != ctrKey || ctrKeyBytes == null) {
                byte[] raw = encoded(key);
                if (ctrKeyBytes != null) {
                    Arrays.fill(ctrKeyBytes, (byte) 0);
                }
                ctrKeyBytes = raw;
                ctrKey = key;
            }
            return MemorySegment.ofArray(ctrKeyBytes);
        }
    }

    /** Frees a thread's native contexts. Holds no reference to the {@link ThreadState} it cleans up. */
    private record Release(MethodHandle cipherFree, MethodHandle aeadFree, long cipherCtx, MemorySegment aeadSlot) implements Runnable {
        @Override
        public void run() {
            try {
                cipherFree.invokeExact(MemorySegment.ofAddress(cipherCtx));
                MemorySegment aeadCtx = aeadSlot.get(ValueLayout.ADDRESS, 0);
                if (aeadCtx.equals(MemorySegment.NULL) == false) {
                    aeadFree.invokeExact(aeadCtx);
                }
            } catch (Throwable ignored) {
                // best effort
            }
        }
    }

    private static byte[] encoded(Key key) throws GeneralSecurityException {
        byte[] raw = key.getEncoded();
        if (raw == null || raw.length != KEY_LENGTH) {
            throw new GeneralSecurityException("expected a 32-byte AES key");
        }
        return raw;
    }

    private static void checkSizes(MemorySegment in, MemorySegment out, MemorySegment entry) {
        if (out.byteSize() != in.byteSize()) {
            throw new IllegalArgumentException("output is " + out.byteSize() + " bytes for " + in.byteSize() + " input bytes");
        }
        if (entry.byteSize() != ENTRY_LENGTH) {
            throw new IllegalArgumentException("nonce-and-tag entry must be " + ENTRY_LENGTH + " bytes");
        }
    }

