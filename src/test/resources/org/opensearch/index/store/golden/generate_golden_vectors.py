"""
Independent reference implementation of the OSEF v2 on-disk format, used to
generate the known-answer vectors in KeyDerivationKnownAnswerTests,
ChunkCipherKnownAnswerTests and
EncryptionFooterKnownAnswerTests, and the
committed golden file golden-v3.osef.

v3 layout: [ciphertext][one 28-byte nonce || GCM tag entry per 8 KiB chunk][footer].
Each chunk is sealed with AES-256-GCM under the file key, a random 12-byte nonce
(generated by the JCE provider when writing; fixed test nonces here) and the
big-endian 64-bit chunk index as AAD. The footer auth tag has its own random
nonce, stored at the start of the footer data; the AAD is the footer data after
the nonce (GCM authenticates the nonce itself, and in FIPS mode the module
generates it while sealing).

It deliberately shares no code with the plugin: the SP 800-108 KDF is written
out with Python's hmac module and AES-GCM comes from the `cryptography`
package. If the Java implementation and this script ever disagree, the
on-disk format has changed and existing encrypted indices may no longer be
readable.

Usage: python3 generate_golden_vectors.py [output-dir]
Requires: pip install cryptography
"""
import hashlib
import hmac
import os
import struct
import sys

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

MASTER_KEY = bytes(range(0x00, 0x20))  # 32 bytes
MESSAGE_ID = bytes(range(0xA0, 0xB0))  # 16 bytes
ALGORITHM_ID = 1  # AES_256_GCM_CTR
MAGIC = b"OSEF"
GOLDEN_PLAINTEXT_LENGTH = 20000  # two full chunks and a 3616-byte tail


def kdf_sha384(key, context, label, length):
    # NIST SP 800-108r1 counter mode, HMAC-SHA-384 PRF, 32-bit counter first:
    # K(i) = HMAC(key, [i]_32 || label || 0x00 || context || [L]_32), L in bits.
    fixed = label + b"\x00" + context + struct.pack(">I", length * 8)
    okm, i = b"", 1
    while len(okm) < length:
        okm += hmac.new(key, struct.pack(">I", i) + fixed, hashlib.sha384).digest()
        i += 1
    return okm[:length]


def file_key(master_key, message_id):
    return kdf_sha384(master_key, message_id, b"file-encryption", 32)


def frame_base_iv(master_key, message_id, frame_number):
    # KDF with a "frame-N" context. No longer used by the file format; kept as an
    # extra KDF vector for KeyDerivationKnownAnswerTests.
    return kdf_sha384(master_key, message_id, b"frame-%d" % frame_number, 16)


def translog_base_iv(master_key, translog_uuid):
    padded = translog_uuid.encode("utf-8")[:16].ljust(16, b"\x00")
    return kdf_sha384(master_key, padded, b"translog-base-iv", 16)


CHUNK_SIZE = 1 << 13  # ChunkCipher.CHUNK_SIZE


def test_nonce(name):
    # The plugin draws nonces from the provider's DRBG; the vectors use fixed ones.
    return hashlib.sha256(name).digest()[:12]


def chunk_aad(chunk_index):
    # ChunkCipher: the big-endian 64-bit chunk index.
    return struct.pack(">Q", chunk_index)


def seal_chunk(key, chunk_index, nonce, plaintext):
    """Returns (ciphertext, entry) where entry = nonce || tag."""
    sealed = AESGCM(key).encrypt(nonce, plaintext, chunk_aad(chunk_index))
    return sealed[:-16], nonce + sealed[-16:]


def seal_chunks(key, plaintext, prefix):
    """Seals plaintext chunk by chunk; returns (ciphertext, [entries])."""
    ciphertext, entries = b"", []
    for i in range(0, len(plaintext), CHUNK_SIZE):
        index = i // CHUNK_SIZE
        ct, entry = seal_chunk(key, index, test_nonce(b"%s-%d" % (prefix, index)), plaintext[i : i + CHUNK_SIZE])
        ciphertext += ct
        entries.append(entry)
    return ciphertext, entries


def golden_plaintext(length):
    return bytes((i * 31 + 7) & 0xFF for i in range(length))


def footer_bytes(key, message_id, data_length):
    footer_nonce = test_nonce(b"golden-footer")
    body = footer_nonce
    body += struct.pack(">q", data_length)
    body += struct.pack(">i", CHUNK_SIZE)
    body += message_id
    body += b""  # KeyMetadata (empty)
    body += struct.pack(">h", 0)  # KeyMetadataLength
    body += struct.pack(">h", ALGORITHM_ID)
    body += struct.pack(">i", 16 + len(body) + 4 + 4)  # FooterLength incl. auth tag
    body += MAGIC
    # empty plaintext, footer data after the nonce as AAD
    auth_tag = AESGCM(key).encrypt(footer_nonce, b"", body[len(footer_nonce):])
    return auth_tag + body


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    fk = file_key(MASTER_KEY, MESSAGE_ID)
    iv0 = frame_base_iv(MASTER_KEY, MESSAGE_ID, 0)
    iv1 = frame_base_iv(MASTER_KEY, MESSAGE_ID, 1)
    print("fileKey            ", fk.hex())
    print("frameBaseIV(0)     ", iv0.hex())
    print("frameBaseIV(1)     ", iv1.hex())
    print("kdf(49, ctx)       ", kdf_sha384(MASTER_KEY, MESSAGE_ID, b"known-answer-test", 49).hex())
    print("translogKey(nonce) ", kdf_sha384(MASTER_KEY, MESSAGE_ID, b"translog-ctr", 32).hex())
    print("translogIV(short)  ", translog_base_iv(MASTER_KEY, "short-uuid").hex())
    print("translogIV(long)   ", translog_base_iv(MASTER_KEY, "8rKGBKWtR9S2bIZ_hXlTQw-trailing").hex())

    chunk_ct, chunk_entries = seal_chunks(fk, golden_plaintext(CHUNK_SIZE + 100), b"kat")
    print("chunk0 nonce       ", chunk_entries[0][:12].hex())
    print("chunk0 ct[0:16]    ", chunk_ct[:16].hex())
    print("chunk0 tag         ", chunk_entries[0][12:].hex())
    print("chunk1 nonce       ", chunk_entries[1][:12].hex())
    print("chunk1 ct[0:16]    ", chunk_ct[CHUNK_SIZE : CHUNK_SIZE + 16].hex())
    print("chunk1 tag         ", chunk_entries[1][12:].hex())

    plaintext = golden_plaintext(GOLDEN_PLAINTEXT_LENGTH)
    ciphertext, entries = seal_chunks(fk, plaintext, b"golden")
    footer = footer_bytes(fk, MESSAGE_ID, len(plaintext))
    print("golden ct[0:32]    ", ciphertext[:32].hex())
    for i, entry in enumerate(entries):
        print("golden entry %d     " % i, entry.hex())
    print("footer (%d bytes)  " % len(footer), footer.hex())

    with open(os.path.join(out_dir, "golden-v3.osef"), "wb") as f:
        f.write(ciphertext + b"".join(entries) + footer)


if __name__ == "__main__":
    main()
